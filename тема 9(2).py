import math

R = float(input("Введіть зовнішній радіус (R): "))
r = float(input("Введіть внутрішній радіус (r): "))

if R > r > 0:
    s = math.pi * (R**2 - r**2)
    print(f"Площа кільця: {s:.2f}")
else:
    print("Помилка: радіуси мають бути додатними, а зовнішній радіус — більшим за внутрішній.")